import assert from "node:assert/strict";
import {createForehead,askCategory,answerCategory,skipForehead,submitGuess,foreheadView} from "./forehead.js";
import {CATEGORY_TREE,categoryOptions,MAX_HINT_LEVELS} from "./foreheadCategories.js";
const start=1000000;
const side=(0 as 0|1);
const s=createForehead({difficulty:"easy",durationSeconds:180,categories:["Animal","Place"]},start);
s.turn=side;s.words[side]="DOG";s.clockAt=start;
assert.equal(MAX_HINT_LEVELS,3);
for(const root of Object.keys(CATEGORY_TREE)){
 const children=categoryOptions([root]);assert.ok(children.length>=2,root+" missing children");
 for(const child of children)assert.ok(categoryOptions([root,child]).length>=3,root+" > "+child+" has no third tier");
}
assert.equal(categoryOptions(["Animal","Land","Four legs"]).length,0);
assert.equal(askCategory(s,side,"Land",start+100),false,"Cannot bypass root tier");
assert.equal(askCategory(s,side,"Animal",start+200),true);
let id=s.pending!.id;
assert.equal(askCategory(s,side,"Food",start+300),false,"Cannot stack pending questions");
assert.equal(answerCategory(s,side,{id,yes:true},start+400),false,"Guesser cannot answer own question");
assert.equal(answerCategory(s,1,{id,yes:false},start+400),true);
assert.deepEqual(s.hints,[],"No does not confirm a step");
assert.ok(s.asked.includes("Animal"),"No keeps asked option at tier 1");
assert.equal(askCategory(s,side,"Animal",start+500),false,"Cannot retry same NO");
assert.equal(askCategory(s,side,"Food",start+600),true);
id=s.pending!.id;
assert.equal(answerCategory(s,1,{id,yes:false},start+650),true);
assert.deepEqual(s.hints,[]);
assert.equal(askCategory(s,side,"Plant",start+700),true);
id=s.pending!.id;
assert.equal(answerCategory(s,1,{id,yes:false},start+750),true);
// Simulate different chosen word; restart hierarchy for clean Animal sample.
assert.equal(skipForehead(s,side,start+1000),true);
const newGuesser=s.turn;
assert.deepEqual(s.hints,[]);assert.deepEqual(s.asked,[]);
const later=start+1200;
assert.equal(askCategory(s,newGuesser,"Animal",later),true);
id=s.pending!.id;
assert.equal(answerCategory(s,(1-newGuesser) as 0|1,{id,yes:true},later+100),true);
assert.deepEqual(s.hints,["Animal"]);
assert.deepEqual(s.asked,[]);
assert.equal(askCategory(s,newGuesser,"Four legs",later+200),false,"Third level cannot be asked at level 2");
assert.equal(askCategory(s,newGuesser,"Sea",later+300),true);
id=s.pending!.id;
assert.equal(answerCategory(s,(1-newGuesser) as 0|1,{id,yes:false},later+400),true);
assert.deepEqual(s.hints,["Animal"]);
assert.equal(askCategory(s,newGuesser,"Sea",later+450),false);
assert.equal(askCategory(s,newGuesser,"Land",later+500),true);
id=s.pending!.id;
assert.equal(answerCategory(s,(1-newGuesser) as 0|1,{id,yes:true},later+600),true);
assert.deepEqual(s.hints,["Animal","Land"]);
assert.equal(askCategory(s,newGuesser,"Fins",later+700),false,"Cannot ask sea-specific trait under land");
assert.equal(askCategory(s,newGuesser,"Four legs",later+800),true);
id=s.pending!.id;
assert.equal(answerCategory(s,(1-newGuesser) as 0|1,{id,yes:true},later+900),true);
assert.deepEqual(s.hints,["Animal","Land","Four legs"]);
assert.deepEqual(foreheadView(s,newGuesser,later+1000).hints,["Animal","Land","Four legs"]);
assert.equal(foreheadView(s,newGuesser,later+1000).otherWord,"");
assert.equal(askCategory(s,newGuesser,"Fur",later+1100),false,"Fourth category prohibited");
assert.equal(s.pending,null);
const word=s.words[newGuesser];
assert.equal(submitGuess(s,newGuesser,word,later+1400),"correct","Word guessing stays available after 3 hints");
assert.deepEqual(s.hints,[],"New word resets category trail");
assert.equal(s.asked.length,0);
assert.equal(askCategory(s,s.turn,"Animal",later+1500),true,"New guesser starts fresh at root");
console.log("PASS all root branches, 3-tier hierarchy, NO stays at tier, YES unlocks correct tier, no fourth category, reset after turn");
