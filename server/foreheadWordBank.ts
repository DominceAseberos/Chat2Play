export function selectedWordPool(categories:readonly GameCategory[],difficulty:Difficulty):string[]{
 return [...new Set(categories.flatMap(category=>POOLS[category][difficulty]))];
}
export function validGameCategories(raw:unknown):GameCategory[]|null{
 if(!Array.isArray(raw)||raw.length<1||raw.length>GAME_CATEGORIES.length
  ||raw.some(v=>typeof v!=="string"||!GAME_CATEGORIES.includes(v as GameCategory))
  ||new Set(raw).size!==raw.length)return null;
 return raw as GameCategory[];
}
